const STRINGS = { en: EN, de: DE };

export function detectLanguage() {
  try {
    const saved = localStorage.getItem('sjb_lang');
    if (saved && STRINGS[saved]) return saved;
  } catch (e) { /* storage blocked */ }
  const nav = (typeof navigator !== 'undefined' && navigator.language) || '';
  return nav.startsWith('de') ? 'de' : 'en';
}

let currentLang = detectLanguage();

export function t(key) {
  return (STRINGS[currentLang] && STRINGS[currentLang][key]) || EN[key] || key;
}

export function setLanguage(lang) {
  currentLang = STRINGS[lang] ? lang : 'en';
  try { localStorage.setItem('sjb_lang', currentLang); } catch (e) { /* storage blocked */ }
  if (typeof window !== 'undefined' && window.dispatchEvent) {
    window.dispatchEvent(new CustomEvent('languagechange', { detail: currentLang }));
  }
}

export function getLanguage() { return currentLang; }

/** Replace the text of every [data-i18n] element inside a root. */
export function applyTranslations(root) {
  const scope = root || (typeof document !== 'undefined' ? document : null);
  if (!scope || !scope.querySelectorAll) return;
  scope.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (!key) return;
    if (el.tagName === 'INPUT' && (el.type === 'text' || el.type === 'search')) el.placeholder = t(key);
    else el.textContent = t(key);
  });
  // A name that does not depend on visible text. Hiding a label with
  // display:none removes it from the accessibility tree as well as from the
  // screen, so the two view tabs lost their names entirely below 900px.
  scope.querySelectorAll('[data-i18n-label]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nLabel));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
    if (!el.getAttribute('aria-label')) el.setAttribute('aria-label', t(el.dataset.i18nTitle));
  });
  if (typeof document !== 'undefined' && document.documentElement) document.documentElement.lang = currentLang;
}
